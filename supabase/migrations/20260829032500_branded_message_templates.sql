-- Branded message template foundation.
-- Source-only until explicitly reviewed and rolled out.
-- No outbound provider calls, email sending, unsubscribe handling or n8n activation live here.

create table if not exists public.message_templates (
  id uuid primary key default gen_random_uuid(),
  workspace_id uuid not null
    references public.workspaces(id) on delete cascade,
  template_key text not null
    check (
      char_length(template_key) between 3 and 80
      and template_key ~ '^[a-z0-9]+(?:[a-z0-9-]*[a-z0-9])?$'
    ),
  name text not null
    check (char_length(btrim(name)) between 1 and 120),
  channel text not null default 'email'
    check (channel = 'email'),
  purpose text not null default 'follow_up'
    check (purpose in ('follow_up', 're_engagement', 'custom')),
  subject_template text not null
    check (char_length(subject_template) between 1 and 300),
  body_template text not null
    check (char_length(body_template) between 1 and 12000),
  tone text not null default 'friendly'
    check (tone in ('professional', 'friendly', 'warm', 'concise')),
  is_enabled boolean not null default true,
  is_default boolean not null default false,
  version integer not null default 1
    check (version >= 1),
  created_by uuid
    references auth.users(id) on delete set null
    default auth.uid(),
  updated_by uuid
    references auth.users(id) on delete set null
    default auth.uid(),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (workspace_id, template_key)
);

comment on table public.message_templates is
  'Workspace-scoped plain-text message templates. Rendering is deterministic and outbound delivery is handled by a separate future layer.';
comment on column public.message_templates.template_key is
  'Stable machine identifier for future automation references. Immutable after insert.';
comment on column public.message_templates.subject_template is
  'Plain-text email subject template. HTML is not accepted by the template editor.';
comment on column public.message_templates.body_template is
  'Plain-text body template. Future outbound HTML must be generated by a controlled renderer, not user-authored HTML.';
comment on column public.message_templates.version is
  'Monotonic revision number incremented by the database whenever an editable template row changes.';

create index if not exists message_templates_workspace_purpose_idx
  on public.message_templates (workspace_id, purpose, is_enabled);

create unique index if not exists message_templates_one_default_per_purpose_idx
  on public.message_templates (workspace_id, channel, purpose)
  where is_default;

alter table public.message_templates enable row level security;

drop policy if exists message_templates_member_read
  on public.message_templates;
create policy message_templates_member_read
on public.message_templates
for select
to authenticated
using (
  (select private.is_workspace_member(message_templates.workspace_id))
);

drop policy if exists message_templates_admin_insert
  on public.message_templates;
create policy message_templates_admin_insert
on public.message_templates
for insert
to authenticated
with check (
  (select private.is_workspace_member(
    message_templates.workspace_id,
    array['owner'::text, 'admin'::text]
  ))
);

drop policy if exists message_templates_admin_update
  on public.message_templates;
create policy message_templates_admin_update
on public.message_templates
for update
to authenticated
using (
  (select private.is_workspace_member(
    message_templates.workspace_id,
    array['owner'::text, 'admin'::text]
  ))
)
with check (
  (select private.is_workspace_member(
    message_templates.workspace_id,
    array['owner'::text, 'admin'::text]
  ))
);

-- Hard delete is intentionally unavailable in v1. Templates can be disabled.
-- This preserves stable automation references until a recovery/history UX exists.
drop policy if exists message_templates_admin_delete
  on public.message_templates;

