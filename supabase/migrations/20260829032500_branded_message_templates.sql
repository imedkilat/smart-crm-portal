create or replace function private.bump_message_template_revision()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  if new.template_key is distinct from old.template_key then
    raise exception 'message template key is immutable'
      using errcode = '22023';
  end if;

  new.version := old.version + 1;
  new.updated_at := now();
  new.updated_by := auth.uid();
  return new;
end;
$$;

revoke all on function private.bump_message_template_revision() from public;
revoke all on function private.bump_message_template_revision() from anon;
revoke all on function private.bump_message_template_revision() from authenticated;

drop trigger if exists trg_message_templates_revision
  on public.message_templates;
create trigger trg_message_templates_revision
before update on public.message_templates
for each row execute function private.bump_message_template_revision();

insert into public.message_templates (
  workspace_id,
  template_key,
  name,
  purpose,
  subject_template,
  body_template,
  tone,
  is_enabled,
  is_default
)
select
  w.id,
  seed.template_key,
  seed.name,
  seed.purpose,
  seed.subject_template,
  seed.body_template,
  seed.tone,
  true,
  true
from public.workspaces w
cross join (
  values
    (
      'hot-follow-up'::text,
      'Hot lead follow-up'::text,
      'follow_up'::text,
      'Quick follow-up, {{lead.first_name}}'::text,
      E'Hi {{lead.first_name}},\n\nThanks for reaching out to {{workspace.company_name}}. I wanted to follow up while your request is still fresh. Reply here if you would like us to help with the next step.\n\n{{workspace.email_signature}}'::text,
      'friendly'::text
    ),
    (
      'warm-re-engagement'::text,
      'Warm lead re-engagement'::text,
      're_engagement'::text,
      'Still interested, {{lead.first_name}}?'::text,
      E'Hi {{lead.first_name}},\n\nJust checking back in from {{workspace.company_name}}. If this is still something you are considering, reply when the timing is right and our team can pick it back up.\n\n{{workspace.email_signature}}'::text,
      'warm'::text
    )
) as seed(template_key, name, purpose, subject_template, body_template, tone)
on conflict (workspace_id, template_key) do nothing;

